class Pipeline_spp_ocr
{
    public function fields()
    {
        return array(
            'VehicleOrVessel'=>array('No Polisi / Nama Kapal','text',200),
            'ShipmentNo'=>array('Shipment No','text',100),
            'DriverName'=>array('Nama Pengemudi','text',150),
            'Buyer'=>array('Pembeli','text',500),
            'Destination'=>array('Tujuan','textarea',1000),
            'ProductName'=>array('Product','text',150),
            'SONumber'=>array('Nomor SO','text',100),
            'LONumber'=>array('Nomor LO','text',100),
            'OrderedLiters'=>array('Jml Pesanan (liter)','number',30),
            'DensityTemperature'=>array('Density & Temp (OBS)','text',150),
            'DeliveryDate'=>array('Tgl Pengiriman','date',10),
            'DepotExitTime'=>array('Jam Keluar Depot','time',5),
            'SealNumbers'=>array('Nomor Segel','text',500)
        );
    }

    public function read($path)
    {
        if(!function_exists('proc_open'))throw new RuntimeException('OCR memerlukan izin proc_open pada server.');
        $temporary=tempnam(sys_get_temp_dir(),'pipeline_spp_');
        if (!$temporary || !@copy($path,$temporary)) {
            if ($temporary && is_file($temporary)) unlink($temporary);
            throw new RuntimeException('File sementara OCR tidak dapat dibuat.');
        }
        $process=null; $outputFile=tempnam(sys_get_temp_dir(),'spp_out_'); $errorFile=tempnam(sys_get_temp_dir(),'spp_err_');
        try {
            if (!$outputFile || !$errorFile) throw new RuntimeException('Penyimpanan sementara OCR tidak tersedia.');
            // Both paths are generated by the server, never supplied as command text by a user.
            $script=realpath(APPPATH.'scripts/pipeline_spp_ocr.ps1');
            if (!$script) throw new RuntimeException('Script OCR tidak tersedia.');
            $powershell=(getenv('SystemRoot')?:'C:\\Windows').'\\System32\\WindowsPowerShell\\v1.0\\powershell.exe';
            $command=escapeshellarg($powershell).' -NoProfile -NonInteractive -ExecutionPolicy Bypass -File '.escapeshellarg($script).' -ImagePath '.escapeshellarg($temporary);
            if(DIRECTORY_SEPARATOR!=='\\'||getenv('SPP_OCR_ENGINE')==='tesseract'){$python=getenv('SPP_OCR_PYTHON')?:'python3';$script=APPPATH.'scripts/pipeline_spp_ocr.py';$command=escapeshellarg($python).' '.escapeshellarg($script).' --input '.escapeshellarg($temporary);}
            // File descriptors avoid the blocking-pipe limitation of PHP 7.3 on Windows.
            $process=proc_open($command,array(0=>array('pipe','r'),1=>array('file',$outputFile,'w'),2=>array('file',$errorFile,'w')),$pipes,null,null,array('bypass_shell'=>true));
            if (!is_resource($process)) throw new RuntimeException('OCR tidak dapat dijalankan.');
            fclose($pipes[0]); $start=microtime(true); $timeout=false;
            do {
                $status=proc_get_status($process);
                if (!$status['running']) break;
                if (microtime(true)-$start>75) { $timeout=true; proc_terminate($process); break; }
                usleep(50000);
            } while(true);
            proc_close($process); $process=null;
            $output=file_get_contents($outputFile,false,null,0,2*1024*1024);
            $payload=json_decode(ltrim(trim($output),"\xEF\xBB\xBF"),true);
            if ($timeout || !$payload || empty($payload['ok'])) throw new RuntimeException('OCR belum berhasil. Foto tetap tersimpan; coba baca ulang atau isi hasilnya secara manual.');
            if(!empty($payload['candidates'])){
                $results=array();foreach($payload['candidates'] as $candidate)$results[]=$this->parse($candidate);
                usort($results,function($a,$b){return count(array_filter($b['fields'],function($v){return $v!=='';}))<=>count(array_filter($a['fields'],function($v){return $v!=='';}));});
                $result=$results[0];foreach(array_slice($results,1) as $other)foreach($other['fields'] as $key=>$value){if($result['fields'][$key]===''&&$value!=='')$result['fields'][$key]=$value;elseif($value!==''&&$result['fields'][$key]!==''&&(string)$value!==(string)$result['fields'][$key])$result['warnings'][]='Bacaan alternatif berbeda pada '.$this->fields()[$key][0].'; cocokkan dengan dokumen.';}
                $result['warnings']=array_values(array_filter($result['warnings'],function($warning)use($result){foreach($this->fields() as $key=>$meta)if($warning===$meta[0].' kosong / belum terbaca; periksa foto.'&&$result['fields'][$key]!=='')return false;return true;}));
                $result['warnings']=array_values(array_unique(array_merge($result['warnings'],isset($payload['warnings'])?$payload['warnings']:array())));
            }else $result=$this->parse($payload);if(isset($payload['pdfPages'])&&(int)$payload['pdfPages']>1)$result['warnings'][]='PDF memiliki '.(int)$payload['pdfPages'].' halaman. Auto Fill membaca halaman pertama saja; unggah setiap SPP secara terpisah.';$result['pdf_pages']=$payload['pdfPages']??null;return $result;
        } finally {
            if (is_resource($process)) { proc_terminate($process); proc_close($process); }
            foreach(array($temporary,$outputFile,$errorFile) as $file) if ($file && is_file($file)) unlink($file);
        }
    }

    private function rows($payload)
    {
        if (empty($payload['words'])) return preg_split('/\R/u',isset($payload['text'])?$payload['text']:'');
        $words=$payload['words'];
        usort($words,function($a,$b){return ($a['y']+$a['height']/2)<=>($b['y']+$b['height']/2);});
        $rows=array();
        foreach($words as $word) {
            $cy=$word['y']+$word['height']/2; $last=count($rows)-1;
            if ($last<0 || abs($rows[$last]['cy']-$cy)>max(6,min($rows[$last]['height'],$word['height'])*0.55)) {
                $rows[]=array('cy'=>$cy,'height'=>$word['height'],'words'=>array($word));
            } else $rows[$last]['words'][]=$word;
        }
        $lines=array();
        foreach($rows as $row) {
            usort($row['words'],function($a,$b){return $a['x']<=>$b['x'];});
            $lines[]=implode(' ',array_column($row['words'],'text'));
        }
        return $lines;
    }

    public function parse($payload)
    {
        $fields=array_fill_keys(array_keys($this->fields()),''); $active=null;
        $patterns=array(
            'VehicleOrVessel'=>'N[O0](?:M[O0]R)?\s*P[O0]L[Il1]S[Il1].*?NAMA\s*KAPAL',
            'ShipmentNo'=>'SH[Il1]PMENT\s*N[O0]',
            'DriverName'=>'NAMA\s*PENGE[\s-]*MU[DO][Il1]',
            'Buyer'=>'PEM[B8]EL[Il1]', 'Destination'=>'TUJUAN', 'ProductName'=>'PR[O0]D(?:U|[Il1][\s-]*J)[KC]T?',
            'SONumber'=>'N[O0]M[O0]R\s*S[O0]', 'LONumber'=>'N[O0]M[O0]R\s*L[O0]',
            'OrderedLiters'=>'JM[LU1]\s*PE(?:ME)?SANAN',
            'DensityTemperature'=>'DENS[Il1]TY\s*[&8B]?\s*TEM[P]?\s*[\(\[C]?[O0]BS[\)\]]?',
            'DeliveryDate'=>'T[GO0]L\s*PENG[Il1\[]R[Il1]MAN',
            'DepotExitTime'=>'JAM\s*KE[LIl1][\s-]*(?:U|[Il1][\s-]*J)AR\s*DEP[O0]T', 'SealNumbers'=>'N[O0]M[O0]R\s*SEGEL'
        );
        $lines=$this->rows($payload);
        foreach($lines as $line) {
            $line=trim($line);
            if (preg_match('/HARUS\s*D[Il1][Il1]S[Il1]|PETUGAS\s*LAPANGAN|JAM\s*T[Il1]BA|TANDA\s*TANGAN/iu',$line)) break;
            $matched=false;
            foreach($patterns as $key=>$pattern) {
                if (preg_match('/^[\s:;.]*'.$pattern.'\s*[:;.\-]?\s*(.*)$/iu',$line,$match)) {
                    // Only the printed header value is used; never replace it with the field-work section.
                    if ($fields[$key]==='') $fields[$key]=trim($match[1]," \t:;.");
                    $active=$key; $matched=true; break;
                }
            }
            if (!$matched && in_array($active,array('Buyer','Destination'),true) && $line!=='') $fields[$active].=' '.$line;
        }
        $warnings=array();
        if ($fields['OrderedLiters']!=='') {
            $v=preg_replace('/\s*(?:Ltr|Liter|L)\.?\s*$/iu','',$fields['OrderedLiters']);
            $v=$this->decimal($v,true);
            if ($v===null || $v<=0) { $warnings[]='Jml Pesanan belum terbaca sebagai volume yang valid.'; $fields['OrderedLiters']=''; }
            else $fields['OrderedLiters']=$v;
        }
        if ($fields['DeliveryDate']!=='') {
            $value=str_replace(',','.',preg_replace('/\s+/','',$fields['DeliveryDate']));
            if (preg_match('/^(\d{2})(\d{2})[.\/-](\d{4})$/D',$value,$m)) $value=$m[1].'.'.$m[2].'.'.$m[3];
            if (preg_match('/^(\d{2})[.\/-](\d{2})(\d{4})$/D',$value,$m)) {
                $value=$m[1].'.'.$m[2].'.'.$m[3];$warnings[]='Pemisah tanggal dipulihkan dari OCR; periksa foto.';
            }
            $date=null;
            foreach(array('!d.m.Y','!d/m/Y','!d-m-Y','!Y-m-d') as $format) {
                $d=DateTime::createFromFormat($format,$value); $errors=DateTime::getLastErrors();
                if ($d && (!$errors || (!$errors['warning_count'] && !$errors['error_count']))) {$date=$d->format('Y-m-d');break;}
            }
            $fields['DeliveryDate']=$date?:'';
        }
        if ($fields['DepotExitTime']!=='') {
            $v=trim($fields['DepotExitTime']);
            if (preg_match('/^(\d{1,2})\s*[:. ]\s*(\d{2})$/D',$v,$m) || preg_match('/^(\d{2})(\d{2})$/D',$v,$m)) {
                $fields['DepotExitTime']=((int)$m[1]<24 && (int)$m[2]<60)?sprintf('%02d:%02d',$m[1],$m[2]):'';
            } else $fields['DepotExitTime']='';
        }
        if (preg_match('/^0[ . ,]*(\d{3,6})\s*[&8@]\s*(\d+(?:[.,]\d+)?)/u',$fields['DensityTemperature'],$m)) {
            $fields['DensityTemperature']='0.'.$m[1].' & '.$m[2].' Celsius';
            $warnings[]='Titik desimal density dipulihkan dari OCR; cocokkan lagi dengan foto.';
        }
        if ($fields['ProductName']!=='') $warnings[]='Periksa nama produk: huruf B/S dan angka 3/5 dapat tertukar pada foto.';
        if ($fields['VehicleOrVessel']!=='') $warnings[]='Cocokkan No Polisi / Nama Kapal karakter demi karakter dengan foto.';
        foreach($this->fields() as $key=>$meta) {
            $fields[$key]=mb_substr(trim((string)$fields[$key]),0,$meta[2]);
            if ($fields[$key]==='') $warnings[]=$meta[0].' kosong / belum terbaca; periksa foto.';
        }
        return array('fields'=>$fields,'warnings'=>$warnings,'text'=>implode("\n",$lines));
    }

    private function decimal($value,$volume=false)
    {
        $value=preg_replace('/\s+/','',trim((string)$value));
        if ($volume && preg_match('/^\d{1,3}(?:\.\d{3})+(?:,\d{1,3})?$/D',$value)) $value=str_replace('.','',$value);
        $value=str_replace(',','.',$value);
        return preg_match('/^\d+(?:\.\d{1,6})?$/D',$value)?(float)$value:null;
    }

    public function validate($input)
    {
        $fields=array();
        foreach($this->fields() as $key=>$meta) {
            $value=isset($input[$key])?$input[$key]:'';
            if (!is_string($value) || mb_strlen($value)>$meta[2]) throw new InvalidArgumentException($meta[0].' tidak valid / terlalu panjang.');
            $fields[$key]=trim($value);
        }
        $volume=$fields['OrderedLiters']===''?null:$this->decimal($fields['OrderedLiters'],false);
        if ($fields['OrderedLiters']!=='' && ($volume===null || $volume<=0 || $volume>1000000000 || round($volume,3)!=$volume)) throw new InvalidArgumentException('Jml Pesanan harus lebih dari nol, maksimal 3 desimal.');
        $fields['OrderedLiters']=$volume;
        if ($fields['DeliveryDate']!=='') {
            $d=DateTime::createFromFormat('!Y-m-d',$fields['DeliveryDate']);
            if (!$d || $d->format('Y-m-d')!==$fields['DeliveryDate']) throw new InvalidArgumentException('Tgl Pengiriman tidak valid.');
        } else $fields['DeliveryDate']=null;
        if ($fields['DepotExitTime']!=='' && !preg_match('/^(?:[01]\d|2[0-3]):[0-5]\d$/D',$fields['DepotExitTime'])) throw new InvalidArgumentException('Jam Keluar Depot tidak valid.');
        $fields['DensityObs']=null; $fields['TemperatureObs']=null;
        if (preg_match('/(\d+[.,]\d+)\s*[&8@]\s*(\d+(?:[.,]\d+)?)/u',$fields['DensityTemperature'],$m)) {
            $density=$this->decimal($m[1]); $temperature=$this->decimal($m[2]);
            if ($density>0 && $density<=2 && $temperature<=100) {$fields['DensityObs']=$density; $fields['TemperatureObs']=$temperature;}
        }
        return $fields;
    }
}
